"""Build the all-in-one Kaggle notebook (notebooks/pipeline_all.ipynb) and optionally push it.

The notebook carries this repo's src/ and configs/ as an embedded zip, so the Kaggle run uses exactly
the committed code. Cells: unpack -> install -> run src.pipeline (all stages, resumable) -> show
tables, figures, demo videos and storyboards.

usage: python kaggle/build_pipeline.py [--push] [--resume-from KERNEL_SLUG ...]
"""
import base64
import io
import json
import os
import subprocess
import sys
import zipfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
USER, SLUG = "chaitrasamant", "ped-intent-pipeline-jaad"

buf = io.BytesIO()
with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
    for top in ("src", "configs"):
        for d, _, fs in os.walk(os.path.join(ROOT, top)):
            for f in fs:
                if f.endswith((".py", ".yaml")):
                    p = os.path.join(d, f)
                    z.write(p, os.path.relpath(p, ROOT))
bundle = base64.b64encode(buf.getvalue()).decode()
commit = subprocess.run(["git", "-C", ROOT, "rev-parse", "--short", "HEAD"], capture_output=True, text=True).stdout.strip()


def md(s):
    return {"cell_type": "markdown", "metadata": {}, "source": s}


def code(s):
    return {"cell_type": "code", "metadata": {}, "execution_count": None, "outputs": [], "source": s}


cells = [
    md("# Cue-aware pedestrian crossing intent and trajectory prediction: JAAD pipeline\n\n"
       f"Built from repo commit `{commit}`. One run: Stage A cue extraction on both GPUs (YOLO11m-pose, "
       "SegFormer-B2 Cityscapes), Stage B training of baselines, main model and ablations (3 seeds), "
       "results tables, surprise mining, and the end-to-end demo (YOLO11m-pose + ByteTrack).\n\n"
       "Benchmarks use JAAD ground-truth boxes and track IDs; the detector and tracker are used only in the demo. "
       "Every number below is produced by this run."),
    code("import base64, io, zipfile, os, sys\n"
         f"BUNDLE = '{bundle}'\n"
         "CODE = '/kaggle/tmp/code'\n"
         "os.makedirs(CODE, exist_ok=True)\n"
         "zipfile.ZipFile(io.BytesIO(base64.b64decode(BUNDLE))).extractall(CODE)\n"
         "print(sorted(os.listdir(CODE)))"),
    code("import subprocess, sys\n"
         "subprocess.run([sys.executable, '-m', 'pip', 'install', '-q', 'ultralytics', 'tabulate'], check=True)\n"
         "import torch; print(torch.__version__, torch.cuda.device_count(), 'GPUs')"),
    code("import os, subprocess, sys\n"
         "env = dict(os.environ, PYTHONPATH='/kaggle/tmp/code', PIPE_WORK='/kaggle/working')\n"
         "p = subprocess.Popen([sys.executable, '-u', '-m', 'src.pipeline', 'all'], cwd='/kaggle/tmp/code', env=env,\n"
         "                     stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)\n"
         "for line in p.stdout:\n"
         "    if 'it/s]' not in line and 'deprecated' not in line:\n"
         "        print(line, end='')\n"
         "p.wait(); print('pipeline exit code', p.returncode)"),
    md("## Results\nTables are read from `results/tables` (generated by `src/eval/analysis.py` and `src/mining/surprise.py`)."),
    code("import glob, json, os\n"
         "from IPython.display import Markdown, Image, Video, display\n"
         "R = '/kaggle/working/results'\n"
         "print(open(f'{R}/STATUS.json').read() if os.path.exists(f'{R}/STATUS.json') else 'no status')\n"
         "for name in ('intent', 'trajectory', 'trajectory_best_of_k'):\n"
         "    f = f'{R}/tables/{name}.md'\n"
         "    if os.path.exists(f):\n"
         "        display(Markdown(f'### {name}\\n' + open(f).read()))\n"
         "for f in ('surprise_summary.csv', 'error_intent_by_condition_main.csv', 'error_traj_fde_by_height_main.csv'):\n"
         "    p = f'{R}/tables/{f}'\n"
         "    if os.path.exists(p):\n"
         "        import pandas as pd; display(Markdown(f'### {f}')); display(pd.read_csv(p))\n"
         "for f in sorted(glob.glob(f'{R}/figures/*.png')):\n"
         "    display(Markdown(f'### {os.path.basename(f)}')); display(Image(f, width=900))"),
    md("## Demo clips\nClips are selected by the fixed rule in `configs/jaad.yaml` (`surprise`), including a failure case. "
       "Cue bars show what the model relied on, not why the person behaved as they did."),
    code("import glob, os\n"
         "from IPython.display import Markdown, Image, Video, display\n"
         "D = '/kaggle/working/results/demo'\n"
         "for f in sorted(glob.glob(f'{D}/*.mp4')):\n"
         "    display(Markdown(f'**{os.path.basename(f)}** ({os.path.getsize(f) / 1e6:.1f} MB)'))\n"
         "    display(Video(f, embed=True, width=800, html_attributes='controls muted'))\n"
         "for f in sorted(glob.glob(f'{D}/*_storyboard.png')):\n"
         "    display(Markdown(f'**{os.path.basename(f)}**')); display(Image(f, width=900))"),
    md("## Optional (live kernel only)\nAn interactive cue toggle would need a running kernel with the trained models loaded; "
       "it is not part of the saved run. The counterfactual video above (`*_counterfactual_no_pose.mp4`) shows the same idea for one cue."),
]
nb = {"cells": cells, "metadata": {"kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"},
                                   "language_info": {"name": "python"}}, "nbformat": 4, "nbformat_minor": 5}
os.makedirs(os.path.join(ROOT, "notebooks"), exist_ok=True)
nb_path = os.path.join(ROOT, "notebooks", "pipeline_all.ipynb")
json.dump(nb, open(nb_path, "w"), indent=1)
print(f"wrote {nb_path} ({os.path.getsize(nb_path) / 1e3:.0f} kB, bundle from commit {commit})")

if "--push" in sys.argv:
    resume = sys.argv[sys.argv.index("--resume-from") + 1:] if "--resume-from" in sys.argv else []
    out = os.path.join(ROOT, "kaggle", "pipeline")
    os.makedirs(out, exist_ok=True)
    json.dump(nb, open(os.path.join(out, "pipeline_all.ipynb"), "w"), indent=1)
    json.dump({"id": f"{USER}/{SLUG}", "title": SLUG, "code_file": "pipeline_all.ipynb", "language": "python",
               "kernel_type": "notebook", "is_private": True, "enable_gpu": True, "enable_internet": True,
               "dataset_sources": [], "competition_sources": [],
               "kernel_sources": [f"{USER}/ped-intent-jaad-download"] + [f"{USER}/{r}" for r in resume]},
              open(os.path.join(out, "kernel-metadata.json"), "w"), indent=1)
    subprocess.run([os.path.join(ROOT, ".venv", "Scripts", "kaggle"), "kernels", "push", "-p", out], check=True)
